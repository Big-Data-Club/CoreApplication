"""Isolated real-PG regression: initial copy, live DML, markers and sequences."""
import threading
import time

from psycopg2 import sql
from psycopg2.errors import LockNotAvailable
from replication import Replica, connect, query, SCHEMA
from runner import Migration

SOURCE = "postgresql://migrator:local-fixture-only@source/postgres?sslmode=disable"
TARGET = "postgresql://migrator:local-fixture-only@target/postgres?sslmode=disable"
DATABASES = ("alpha", "beta", "gamma", "delta", "epsilon", "zeta")


def wait(predicate):
    deadline = time.monotonic() + 90
    while not predicate():
        assert time.monotonic() < deadline, "Replication did not catch up"
        time.sleep(0.25)


def main():
    for url in (SOURCE, TARGET):
        conn = connect(url.replace("//migrator:", "//postgres:"), "postgres")
        query(conn, "CREATE ROLE migrator LOGIN CREATEDB REPLICATION PASSWORD 'local-fixture-only'; GRANT pg_create_subscription TO migrator")
        if url == SOURCE:
            for db in DATABASES:
                query(conn, sql.SQL("CREATE DATABASE {} OWNER migrator").format(sql.Identifier(db)))
        conn.close()
    replicas = []
    scheduler = Migration.__new__(Migration)
    scheduler.active_replicas = []
    for index, database in enumerate(DATABASES):
        source = connect(SOURCE, database)
        query(source, """CREATE TABLE items(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL);
              INSERT INTO items(value) SELECT 'initial-' || i FROM generate_series(1,2000) i;
              CREATE TABLE disposable(id integer PRIMARY KEY); INSERT INTO disposable VALUES (1),(2);
              CREATE SEQUENCE "unused sequence" START 17;
              CREATE SCHEMA "odd schema";
              CREATE TABLE "odd schema"."quoted table"(id integer PRIMARY KEY, value text);
              INSERT INTO "odd schema"."quoted table" VALUES (1,'quoted');
              CREATE MATERIALIZED VIEW item_summary AS
                SELECT count(*) AS total, sum(id)::bigint AS id_sum FROM items WITH DATA;
              CREATE UNIQUE INDEX item_summary_total ON item_summary(total);""")
        replica = Replica(SOURCE, TARGET, database, "a" * 32, index)
        # Unsupported sources must fail before changing the target.
        query(source, "CREATE TABLE missing_identity(value text)")
        try:
            replica.preflight()
            raise AssertionError("Missing replica identity was accepted")
        except RuntimeError as exc:
            assert "replica identity" in str(exc)
        query(source, "DROP TABLE missing_identity")
        replica.preflight()
        if len(scheduler.active_replicas) == 3:
            old = scheduler.active_replicas.pop(0)
            old.pause()
            wait(old.no_workers)
        replica.prepare()
        assert query(replica.guard, "SHOW idle_in_transaction_session_timeout") == [("0",)]
        replica.verify_runtime(SOURCE, "a" * 32)
        replicas.append(replica)
        scheduler.active_replicas.append(replica)
        wait(lambda: all(r.caught_up() for r in scheduler.active_replicas))
        assert query(replica.target, "SELECT count(*) FROM pg_stat_subscription WHERE pid IS NOT NULL")[0][0] <= 4
        source.close()

    errors = []
    def live_writes():
        try:
            for database in DATABASES:
                conn = connect(SOURCE, database)
                for index in range(50):
                    query(conn, "INSERT INTO items(value) VALUES (%s)", ("live-" + str(index),))
                    query(conn, "UPDATE items SET value=%s WHERE id=%s", ("changed-" + str(index), index + 1))
                    query(conn, "DELETE FROM items WHERE id=%s", (index + 100,))
                # The schema guard deliberately blocks DDL/TRUNCATE, while
                # ordinary INSERT/UPDATE/DELETE stay online during initial COPY.
                query(conn, "SET lock_timeout='200ms'")
                try:
                    query(conn, "TRUNCATE disposable")
                    raise AssertionError("Schema guard allowed TRUNCATE")
                except LockNotAvailable:
                    pass
                query(conn, "DELETE FROM disposable")
                conn.close()
        except Exception as exc:
            errors.append(exc)
    writer = threading.Thread(target=live_writes)
    writer.start()
    writer.join()
    assert not errors, errors
    # The first three subscriptions were disabled during the live writes.
    # Resuming them must replay those changes from their retained source slots.
    scheduler.switch_active(replicas[:3])
    wait(lambda: all(r.caught_up() for r in scheduler.active_replicas))
    for replica in replicas[:3]:
        assert query(replica.target, "SELECT count(*) FROM items WHERE value LIKE 'live-%'")[0][0] == 50
    for replica in replicas:
        replica.fence()
    wait(lambda: all(r.barrier_applied() for r in scheduler.active_replicas))
    scheduler.switch_active(replicas[3:])
    wait(lambda: all(r.barrier_applied() for r in scheduler.active_replicas))
    for replica in replicas:
        replica.finalize()
        replica.verify_runtime(TARGET, "a" * 32 + ":final")
        assert query(replica.source, "SELECT * FROM items ORDER BY id") == query(replica.target, "SELECT * FROM items ORDER BY id")
        assert query(replica.target, "SELECT count(*) FROM disposable") == [(0,)]
        assert query(replica.target, 'SELECT * FROM "odd schema"."quoted table"') == [(1, "quoted")]
        assert query(replica.target, "SELECT id_sum FROM item_summary")[0][0] == query(replica.target, "SELECT sum(id) FROM items")[0][0]
        assert query(replica.target, "SELECT id_sum FROM item_summary") != query(replica.source, "SELECT id_sum FROM item_summary")
        source_sequence = query(replica.source, "SELECT last_value,is_called FROM items_id_seq")[0]
        assert query(replica.target, "SELECT last_value,is_called FROM items_id_seq")[0] == source_sequence
        assert query(replica.target, '''SELECT nextval('"unused sequence"')''') == [(17,)]
        assert query(replica.target, "INSERT INTO items(value) VALUES ('after-cutover') RETURNING id")[0][0] > source_sequence[0]
        replica.cleanup()
        assert not query(replica.source, "SELECT 1 FROM pg_replication_slots WHERE slot_name=%s", (replica.name,))
        replica.close()
    print("PASS: six databases on four workers, paused WAL replay, initial COPY, concurrent INSERT/UPDATE/DELETE, materialized view refresh, final barriers, sequences and slot cleanup", flush=True)


if __name__ == "__main__":
    main()
